-- NITRA SPACE / RANDOM. Clerk-authenticated anonymous matching and chat; existing tables stay untouched.
create schema if not exists random_private;
revoke all on schema random_private from public, anon, authenticated;

create table random_private.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  first_name text not null check (char_length(btrim(first_name)) between 1 and 24 and first_name !~ '\s'),
  age smallint not null check (age between 16 and 99),
  age_min smallint not null,
  age_max smallint not null,
  intent text not null check (intent in ('friends','dating')),
  surprise_topic text check (surprise_topic in ('music','events','food','games','city')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (age_min between 16 and 99 and age_max between age_min and 99),
  check ((age < 18 and age_min >= 16 and age_max <= 17 and intent = 'friends') or (age >= 18 and age_min >= 18))
);
create table random_private.sessions (
  user_id uuid primary key references random_private.profiles(user_id) on delete cascade,
  last_seen_at timestamptz not null default now()
);
create table random_private.queue (
  user_id uuid primary key references random_private.profiles(user_id) on delete cascade,
  joined_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);
create index random_queue_waiting_idx on random_private.queue(joined_at);
create table random_private.matches (
  id uuid primary key default gen_random_uuid(),
  user_a uuid not null references random_private.profiles(user_id) on delete cascade,
  user_b uuid not null references random_private.profiles(user_id) on delete cascade,
  state text not null check (state in ('offered','chat','closed')),
  accept_a boolean,
  accept_b boolean,
  mystery_question text not null,
  daily_challenge text not null,
  surprise_topic text,
  close_reason text,
  created_at timestamptz not null default now(),
  last_activity_at timestamptz not null default now(),
  closed_at timestamptz,
  check (user_a < user_b),
  check (state <> 'chat' or (accept_a is true and accept_b is true))
);
create unique index random_one_open_match_per_a on random_private.matches(user_a) where state in ('offered','chat');
create unique index random_one_open_match_per_b on random_private.matches(user_b) where state in ('offered','chat');
create index random_matches_open_state_idx on random_private.matches(state,last_activity_at);
create table random_private.pair_history (
  user_a uuid not null references random_private.profiles(user_id) on delete cascade,
  user_b uuid not null references random_private.profiles(user_id) on delete cascade,
  last_matched_at timestamptz not null default now(),
  primary key (user_a,user_b), check (user_a < user_b)
);
create table random_private.blocks (
  blocker_id uuid not null references random_private.profiles(user_id) on delete cascade,
  blocked_id uuid not null references random_private.profiles(user_id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (blocker_id,blocked_id), check (blocker_id <> blocked_id)
);
create table random_private.reports (
  id uuid primary key default gen_random_uuid(),
  reporter_id uuid not null references random_private.profiles(user_id) on delete cascade,
  reported_id uuid not null references random_private.profiles(user_id) on delete cascade,
  match_id uuid not null references random_private.matches(id) on delete cascade,
  reason text not null check (reason in ('harassment','spam','unsafe','other')),
  created_at timestamptz not null default now(), check (reporter_id <> reported_id)
);
create table random_private.prompts (
