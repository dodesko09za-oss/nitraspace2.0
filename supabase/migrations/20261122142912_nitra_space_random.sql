create or replace function random_private.require_clerk_user()
returns uuid language plpgsql stable set search_path = '' as $$
declare v_uid uuid := auth.uid();
begin
  if v_uid is null
     or coalesce(auth.jwt() -> 'app_metadata' ->> 'auth_provider','') <> 'clerk'
     or coalesce(auth.jwt() -> 'app_metadata' ->> 'clerk_user_id','') = '' then
    raise exception 'RANDOM requires a Nitra Space account signed in through Clerk.' using errcode='28000';
  end if;
  return v_uid;
end;
$$;

create or replace function random_private.daily_challenge()
returns text language sql stable set search_path = '' as $$
  with choices as (
    select p.content,row_number() over(order by p.id)-1 as position,count(*) over() as total
    from random_private.prompts p where p.kind='daily'
  )
  select c.content from choices c
  where c.position=((current_date-date '2000-01-01') % c.total);
$$;

create or replace function random_private.finish_match(p_match_id uuid,p_reason text,p_requeue boolean)
returns void language plpgsql set search_path = '' as $$
declare v_match random_private.matches%rowtype;
begin
  select * into v_match from random_private.matches where id=p_match_id and state in ('offered','chat') for update;
  if not found then return; end if;
  update random_private.matches set state='closed',close_reason=p_reason,closed_at=now(),last_activity_at=now() where id=p_match_id;
  insert into random_private.pair_history(user_a,user_b,last_matched_at)
  values (least(v_match.user_a,v_match.user_b),greatest(v_match.user_a,v_match.user_b),now())
  on conflict (user_a,user_b) do update set last_matched_at=excluded.last_matched_at;
  delete from random_private.queue where user_id in (v_match.user_a,v_match.user_b);
  if p_requeue then
    insert into random_private.queue(user_id,joined_at,last_seen_at)
    select s.user_id,now(),s.last_seen_at from random_private.sessions s
    where s.user_id in (v_match.user_a,v_match.user_b) and s.last_seen_at>now()-interval '45 seconds'
    on conflict (user_id) do update set joined_at=excluded.joined_at,last_seen_at=excluded.last_seen_at;
  end if;
end;
$$;

create or replace function random_private.cleanup_stale()
returns void language plpgsql set search_path = '' as $$
declare v record;
begin
  perform pg_advisory_xact_lock(hashtextextended('nitra-space-random-matchmaking',0));
  delete from random_private.queue where last_seen_at<now()-interval '45 seconds';
  for v in
    select m.id,case when m.state='offered' then 'expired_offer' else 'inactive' end as why
    from random_private.matches m
    where (m.state='offered' and m.created_at<now()-interval '2 minutes')
       or (m.state='chat' and exists (
         select 1 from random_private.sessions s where s.user_id in (m.user_a,m.user_b)
         and s.last_seen_at<now()-interval '15 minutes'
       ))
    for update
  loop
    perform random_private.finish_match(v.id,v.why,true);
  end loop;
end;
$$;

create or replace function random_private.try_match(p_user_id uuid)
returns void language plpgsql set search_path = '' as $$
declare v_candidate uuid; v_question text; v_challenge text; v_topic text;
begin
  perform pg_advisory_xact_lock(hashtextextended('nitra-space-random-matchmaking',0));
  if not exists (select 1 from random_private.queue where user_id=p_user_id and last_seen_at>now()-interval '45 seconds') then return; end if;
  if exists (select 1 from random_private.matches where state in ('offered','chat') and p_user_id in (user_a,user_b)) then return; end if;
  select q.user_id into v_candidate
  from random_private.queue q
  join random_private.profiles candidate on candidate.user_id=q.user_id
  join random_private.profiles seeker on seeker.user_id=p_user_id
  where q.user_id<>p_user_id and q.last_seen_at>now()-interval '45 seconds'
    and candidate.age between seeker.age_min and seeker.age_max
    and seeker.age between candidate.age_min and candidate.age_max
    and candidate.intent=seeker.intent
    and ((candidate.age<18 and seeker.age<18 and candidate.intent='friends') or (candidate.age>=18 and seeker.age>=18))
    and not exists (select 1 from random_private.matches m where m.state in ('offered','chat') and q.user_id in (m.user_a,m.user_b))
    and not exists (select 1 from random_private.pair_history h where h.user_a=least(p_user_id,q.user_id) and h.user_b=greatest(p_user_id,q.user_id) and h.last_matched_at>now()-interval '24 hours')
    and not exists (select 1 from random_private.blocks b where (b.blocker_id=p_user_id and b.blocked_id=q.user_id) or (b.blocker_id=q.user_id and b.blocked_id=p_user_id))
  order by (candidate.surprise_topic is not null and candidate.surprise_topic=seeker.surprise_topic and random()<0.3) desc,q.joined_at asc
  limit 1 for update of q skip locked;
  if v_candidate is null then return; end if;
  select content into v_question from random_private.prompts where kind='mystery' order by random() limit 1;
  v_challenge:=random_private.daily_challenge();
  select case when seeker.surprise_topic=candidate.surprise_topic then seeker.surprise_topic else null end
  into v_topic from random_private.profiles seeker,random_private.profiles candidate
  where seeker.user_id=p_user_id and candidate.user_id=v_candidate;
  insert into random_private.matches(user_a,user_b,state,mystery_question,daily_challenge,surprise_topic)
  values (least(p_user_id,v_candidate),greatest(p_user_id,v_candidate),'offered',v_question,coalesce(v_challenge,'Dnešná výzva: začni rozhovor milou otázkou.'),v_topic);
  delete from random_private.queue where user_id in (p_user_id,v_candidate);
end;
$$;

create or replace function random_private.state_for(p_user_id uuid)
returns jsonb language plpgsql stable set search_path = '' as $$
declare v_match random_private.matches%rowtype; v_other uuid; v_partner random_private.profiles%rowtype;
begin
  select * into v_match from random_private.matches
    where state in ('offered','chat') and p_user_id in (user_a,user_b) order by created_at desc limit 1;
  if found then
    v_other:=case when v_match.user_a=p_user_id then v_match.user_b else v_match.user_a end;
    select * into v_partner from random_private.profiles where user_id=v_other;
    return jsonb_build_object(
      'mode',case when v_match.state='offered' then 'offer' else 'chat' end,
      'match_id',v_match.id,
      'partner',jsonb_build_object('first_name',v_partner.first_name,'age',v_partner.age),
      'question',v_match.mystery_question,'daily_challenge',v_match.daily_challenge,
      'surprise_topic',v_match.surprise_topic,
      'my_accepted',case when v_match.user_a=p_user_id then v_match.accept_a else v_match.accept_b end,
      'partner_accepted',case when v_match.user_a=p_user_id then v_match.accept_b else v_match.accept_a end
    );
  end if;
  if exists (select 1 from random_private.queue where user_id=p_user_id) then return jsonb_build_object('mode','searching'); end if;
  select * into v_match from random_private.matches where state='closed' and p_user_id in (user_a,user_b) order by closed_at desc limit 1;
  if found and v_match.closed_at>now()-interval '3 minutes' then return jsonb_build_object('mode','ended','reason',v_match.close_reason); end if;
  return jsonb_build_object('mode','idle');
end;
$$;

create or replace function public.random_is_chat_member(p_match_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce(auth.jwt() -> 'app_metadata' ->> 'auth_provider','')='clerk'
    and coalesce(auth.jwt() -> 'app_metadata' ->> 'clerk_user_id','') <> ''
    and auth.uid() is not null
    and exists (select 1 from random_private.matches m where m.id=p_match_id and m.state='chat' and auth.uid() in (m.user_a,m.user_b));
$$;
revoke all on function public.random_is_chat_member(uuid) from public,anon;
grant execute on function public.random_is_chat_member(uuid) to authenticated;
create policy random_messages_chat_participants_read on public.random_messages
  for select to authenticated using (public.random_is_chat_member(match_id));
create policy random_typing_chat_participants_read on public.random_typing
  for select to authenticated using (public.random_is_chat_member(match_id));

