create or replace function public.random_join(
  p_first_name text,p_age integer,p_age_min integer,p_age_max integer,
  p_intent text,p_surprise_topic text default 'none'
)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_uid uuid:=random_private.require_clerk_user();
begin
  if exists (select 1 from random_private.matches where state in ('offered','chat') and v_uid in (user_a,user_b)) then
    return random_private.state_for(v_uid);
  end if;
  if p_first_name is null or char_length(btrim(p_first_name)) not between 1 and 24 or btrim(p_first_name) ~ '\s' then
    raise exception 'Zadaj iba krstné meno bez medzier.' using errcode='22023';
  end if;
  if p_age not between 16 and 99 or p_age_min not between 16 and 99 or p_age_max not between p_age_min and 99 then
    raise exception 'Vek alebo preferovaný rozsah nie je platný.' using errcode='22023';
  end if;
  if p_intent not in ('friends','dating') then raise exception 'Vyber, či hľadáš kamarátov alebo zoznámenie.' using errcode='22023'; end if;
  if p_age<18 and (p_age_min<16 or p_age_max>17 or p_intent<>'friends') then
    raise exception 'Používatelia vo veku 16–17 rokov sa párujú iba spolu a na kamarátstvo.' using errcode='22023';
  elsif p_age>=18 and p_age_min<18 then
    raise exception 'Dospelí sa párujú iba s dospelými.' using errcode='22023';
  end if;
  if coalesce(p_surprise_topic,'none') not in ('music','events','food','games','city','none') then
    raise exception 'Vyber jednu z dostupných tém.' using errcode='22023';
  end if;
  insert into random_private.profiles(user_id,first_name,age,age_min,age_max,intent,surprise_topic)
  values (v_uid,btrim(p_first_name),p_age,p_age_min,p_age_max,p_intent,nullif(p_surprise_topic,'none'))
  on conflict (user_id) do update set first_name=excluded.first_name,age=excluded.age,age_min=excluded.age_min,
    age_max=excluded.age_max,intent=excluded.intent,surprise_topic=excluded.surprise_topic,updated_at=now();
  insert into random_private.sessions(user_id,last_seen_at) values(v_uid,now())
  on conflict(user_id) do update set last_seen_at=excluded.last_seen_at;
  perform random_private.cleanup_stale();
  insert into random_private.queue(user_id,joined_at,last_seen_at) values(v_uid,now(),now())
  on conflict(user_id) do update set last_seen_at=excluded.last_seen_at;
  perform random_private.try_match(v_uid);
  return random_private.state_for(v_uid);
end;
$$;

create or replace function public.random_state()
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_uid uuid:=random_private.require_clerk_user();
begin
  insert into random_private.sessions(user_id,last_seen_at)
  select v_uid,now() where exists(select 1 from random_private.profiles where user_id=v_uid)
  on conflict(user_id) do update set last_seen_at=excluded.last_seen_at;
  perform random_private.cleanup_stale();
  perform random_private.try_match(v_uid);
  return random_private.state_for(v_uid);
end;
$$;

create or replace function public.random_respond(p_match_id uuid,p_accept boolean)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_uid uuid:=random_private.require_clerk_user(); v_match random_private.matches%rowtype;
begin
  perform random_private.cleanup_stale();
  select * into v_match from random_private.matches where id=p_match_id and state='offered' and v_uid in (user_a,user_b) for update;
  if not found then raise exception 'Toto spojenie už nie je aktívne.' using errcode='P0002'; end if;
  if v_match.user_a=v_uid then update random_private.matches set accept_a=p_accept where id=p_match_id;
  else update random_private.matches set accept_b=p_accept where id=p_match_id; end if;
  if not p_accept then
    perform random_private.finish_match(p_match_id,'declined',true);
    perform random_private.try_match(v_uid);
  else
    select * into v_match from random_private.matches where id=p_match_id for update;
    if v_match.accept_a is true and v_match.accept_b is true then
      update random_private.matches set state='chat',last_activity_at=now() where id=p_match_id;
      insert into public.random_typing(match_id,user_id,is_typing,updated_at)
      values(p_match_id,v_match.user_a,false,now()),(p_match_id,v_match.user_b,false,now())
      on conflict(match_id,user_id) do update set is_typing=false,updated_at=excluded.updated_at;
    end if;
  end if;
  insert into random_private.sessions(user_id,last_seen_at) values(v_uid,now())
  on conflict(user_id) do update set last_seen_at=excluded.last_seen_at;
  return random_private.state_for(v_uid);
end;
$$;

create or replace function public.random_next()
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_uid uuid:=random_private.require_clerk_user(); v_match_id uuid;
begin
  perform random_private.cleanup_stale();
  select id into v_match_id from random_private.matches where state in ('offered','chat') and v_uid in (user_a,user_b) order by created_at desc limit 1 for update;
  if v_match_id is not null then perform random_private.finish_match(v_match_id,'next',true); end if;
  insert into random_private.sessions(user_id,last_seen_at) values(v_uid,now()) on conflict(user_id) do update set last_seen_at=excluded.last_seen_at;
  insert into random_private.queue(user_id,joined_at,last_seen_at) values(v_uid,now(),now())
  on conflict(user_id) do update set joined_at=excluded.joined_at,last_seen_at=excluded.last_seen_at;
  perform random_private.try_match(v_uid);
  return random_private.state_for(v_uid);
end;
$$;

create or replace function public.random_leave()
returns void language plpgsql security definer set search_path = '' as $$
declare v_uid uuid:=random_private.require_clerk_user(); v_match_id uuid;
begin
  select id into v_match_id from random_private.matches where state in ('offered','chat') and v_uid in (user_a,user_b) order by created_at desc limit 1 for update;
  if v_match_id is not null then perform random_private.finish_match(v_match_id,'ended',false); end if;
  delete from random_private.queue where user_id=v_uid;
end;
$$;

create or replace function public.random_send_message(p_match_id uuid,p_body text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_uid uuid:=random_private.require_clerk_user(); v_message public.random_messages%rowtype; v_count integer;
begin
  if p_body is null or char_length(btrim(p_body)) not between 1 and 1000 then raise exception 'Správa musí mať 1 až 1000 znakov.' using errcode='22023'; end if;
  if not public.random_is_chat_member(p_match_id) then raise exception 'Tento chat už nie je aktívny.' using errcode='42501'; end if;
  select count(*) into v_count from public.random_messages where match_id=p_match_id and sender_id=v_uid and created_at>now()-interval '1 minute';
  if v_count>=30 then raise exception 'Počkaj chvíľu pred ďalšími správami.' using errcode='54000'; end if;
  insert into public.random_messages(match_id,sender_id,body) values(p_match_id,v_uid,btrim(p_body)) returning * into v_message;
  update random_private.matches set last_activity_at=now() where id=p_match_id and state='chat';
  update random_private.sessions set last_seen_at=now() where user_id=v_uid;
  return jsonb_build_object('id',v_message.id,'match_id',v_message.match_id,'sender_id',v_message.sender_id,'body',v_message.body,'created_at',v_message.created_at);
end;
$$;

create or replace function public.random_set_typing(p_match_id uuid,p_is_typing boolean)
returns void language plpgsql security definer set search_path = '' as $$
declare v_uid uuid:=random_private.require_clerk_user();
begin
  if not public.random_is_chat_member(p_match_id) then return; end if;
