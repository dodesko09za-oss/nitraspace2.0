create or replace function public.random_report(p_match_id uuid,p_reason text)
returns void language plpgsql security definer set search_path = '' as $$
declare v_uid uuid:=random_private.require_clerk_user(); v_other uuid;
begin
  if p_reason not in ('harassment','spam','unsafe','other') then raise exception 'Vyber dôvod nahlásenia.' using errcode='22023'; end if;
  select case when user_a=v_uid then user_b else user_a end into v_other
  from random_private.matches where id=p_match_id and state='chat' and v_uid in (user_a,user_b);
  if v_other is null then raise exception 'Tento rozhovor už nie je aktívny.' using errcode='42501'; end if;
  insert into random_private.reports(reporter_id,reported_id,match_id,reason) values(v_uid,v_other,p_match_id,p_reason);
end;
$$;

create or replace function public.random_block(p_match_id uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_uid uuid:=random_private.require_clerk_user(); v_other uuid;
begin
  select case when user_a=v_uid then user_b else user_a end into v_other
  from random_private.matches where id=p_match_id and state in ('offered','chat') and v_uid in (user_a,user_b);
  if v_other is null then raise exception 'Toto spojenie už nie je aktívne.' using errcode='42501'; end if;
  insert into random_private.blocks(blocker_id,blocked_id) values(v_uid,v_other) on conflict do nothing;
  perform random_private.finish_match(p_match_id,'blocked',true);
  perform random_private.try_match(v_uid);
  return random_private.state_for(v_uid);
end;
$$;

